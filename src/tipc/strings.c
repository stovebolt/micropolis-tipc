int GetIndString(char *str, int id, short num)
{
  const char *const *t; int n;
  switch (id) {
  case 301: t = str301; n = sizeof str301 / sizeof *str301; break;
  case 202: t = str202; n = sizeof str202 / sizeof *str202; break;
  case 219: t = str219; n = sizeof str219 / sizeof *str219; break;
  default: str[0] = 0; return 0;
  }
  if (num < 1 || num > n) { str[0] = 0; return 0; }
  strcpy(str, t[num - 1]);
  return 0;
}
